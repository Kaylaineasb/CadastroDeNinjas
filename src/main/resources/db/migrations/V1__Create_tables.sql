CREATE TABLE tb_missoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255),
    dificuldade VARCHAR(255)
);

CREATE TABLE tb_cadastro (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     nome VARCHAR(255),
     idade INT NOT NULL,
     img_url VARCHAR(255),
     email VARCHAR(255) UNIQUE,
     missoes_id BIGINT,
     CONSTRAINT fk_ninja_missoes FOREIGN KEY (missoes_id) REFERENCES tb_missoes(id)
);